-- ContextAI schema for Postgres (Supabase) with pgvector. Idempotent: safe to run on every start.
-- Embeddings are 384-d all-MiniLM-L6-v2 vectors, the same model the local Chroma store uses.
-- pgvector lives in the "extensions" schema (Supabase's recommendation); connections put it on the
-- search_path so vector(384) and the <=> operator resolve.

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists conversations (
    id          text primary key,
    user_id     text not null,
    title       text not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create index if not exists conversations_user_updated on conversations (user_id, updated_at desc);

create table if not exists conversation_history (
    id              bigint generated by default as identity primary key,
    user_id         text not null,
    role            text not null check (role in ('user', 'assistant')),
    message         text not null,
    timestamp       timestamptz not null default now(),
    conversation_id text references conversations (id) on delete cascade,
    metadata        jsonb
);
create index if not exists conversation_history_conversation on conversation_history (conversation_id, id);
create index if not exists conversation_history_user on conversation_history (user_id, id);

create table if not exists reminders (
    id              bigint generated by default as identity primary key,
    user_id         text not null,
    reminder_text   text not null,
    scheduled_time  text not null,
    created_at      timestamptz not null default now(),
    status          text not null default 'pending' check (status in ('pending', 'completed')),
    due_at          timestamptz,
    timezone        text,
    notified_at     timestamptz
);
create index if not exists reminders_user_status on reminders (user_id, status);
create index if not exists reminders_due on reminders (due_at) where status = 'pending' and notified_at is null;

create table if not exists push_subscriptions (
    endpoint    text primary key,
    user_id     text not null,
    p256dh      text not null,
    auth        text not null,
    created_at  timestamptz not null default now()
);
create index if not exists push_subscriptions_user on push_subscriptions (user_id);

create table if not exists memories (
    id          text primary key,
    user_id     text not null,
    fact        text not null,
    embedding   vector(384) not null,
    source      text not null default 'chat',
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create index if not exists memories_user on memories (user_id);
create index if not exists memories_embedding on memories using hnsw (embedding vector_cosine_ops);

create table if not exists document_chunks (
    id              text primary key,
    user_id         text,
    document_id     text not null,
    document_name   text not null,
    page_number     int not null,
    chunk_index     int not null,
    section         text,
    total_pages     int,
    uploaded_at     timestamptz not null default now(),
    content         text not null,
    embedding       vector(384) not null
);
create index if not exists document_chunks_user_doc on document_chunks (user_id, document_id);
create index if not exists document_chunks_embedding on document_chunks using hnsw (embedding vector_cosine_ops);

-- Only the server (direct Postgres connection) may touch these tables. Enabling RLS with no policies
-- blocks Supabase's public REST/GraphQL API (anon and authenticated roles) entirely.
alter table conversations        enable row level security;
alter table conversation_history enable row level security;
alter table reminders            enable row level security;
alter table push_subscriptions   enable row level security;
alter table memories             enable row level security;
alter table document_chunks      enable row level security;
